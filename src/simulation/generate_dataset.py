import argparse
import csv
import random
from datetime import datetime, timedelta, timezone
from pathlib import Path

from src.simulation.machine import Machine
from src.simulation.faults import FaultInjector


FAULT_TYPES = [
    "OVERHEATING",
    "OVERLOAD",
    "SPEED_ANOMALY",
]

MACHINE_TYPES = ["L", "M", "H"]

COLUMNS = [
    "timestamp",
    "machine_id",
    "machine_type",
    "cycle",
    "operating_hours",
    "health",
    "tool_wear",
    "air_temperature",
    "process_temperature",
    "rotational_speed",
    "torque",
    "status",
    "is_anomaly",
    "anomaly_type",
    "data_source",
]


def generate_dataset(
    number_of_machines=20,
    cycles_per_machine=500,
    fault_rate=0.10,
    random_seed=42,
    output_path="data/simulated/sensor_readings.csv",
):
    """Generate a labelled synthetic industrial sensor dataset."""

    if number_of_machines < 1:
        raise ValueError("number_of_machines must be at least 1")

    if cycles_per_machine < 1:
        raise ValueError("cycles_per_machine must be at least 1")

    if not 0 <= fault_rate <= 1:
        raise ValueError("fault_rate must be between 0 and 1")

    rng = random.Random(random_seed)

    output = Path(output_path)
    output.parent.mkdir(parents=True, exist_ok=True)

    start_time = datetime(2026, 1, 1, tzinfo=timezone.utc)

    total_rows = 0
    anomaly_count = 0
    fault_counts = {fault: 0 for fault in FAULT_TYPES}

    status_counts = {
        "NORMAL": 0,
        "WARNING": 0,
        "DEGRADED": 0,
        "CRITICAL": 0,
    }

    with output.open("w", newline="", encoding="utf-8") as file:

        writer = csv.DictWriter(file, fieldnames=COLUMNS)
        writer.writeheader()

        for machine_number in range(1, number_of_machines + 1):

            machine_id = f"MACHINE-{machine_number:03d}"
            machine_type = rng.choice(MACHINE_TYPES)

            machine = Machine(
                machine_id=machine_id,
                machine_type=machine_type,
                random_seed=random_seed + machine_number,
            )

            injector = FaultInjector(
                random_seed=random_seed + machine_number * 100
            )

            for cycle in range(1, cycles_per_machine + 1):

                reading = machine.generate_sensor_reading()

                # Assign a controlled synthetic fault to this observation.
                if rng.random() < fault_rate:

                    fault_type = rng.choice(FAULT_TYPES)

                    reading = injector.inject(
                        reading,
                        fault_type,
                    )

                    anomaly_count += 1
                    fault_counts[fault_type] += 1

                else:
                    reading = injector.normal_reading(reading)

                # Six minutes per simulated operating cycle.
                timestamp = start_time + timedelta(
                    minutes=(cycle - 1) * 6
                )

                reading["timestamp"] = timestamp.isoformat()
                reading["is_anomaly"] = int(reading["is_anomaly"])
                reading["data_source"] = "synthetic_simulator"

                writer.writerow({
                    column: reading[column]
                    for column in COLUMNS
                })

                total_rows += 1
                status_counts[reading["status"]] += 1

    normal_count = total_rows - anomaly_count

    summary = {
        "dataset_name": "Industrial Predictive Maintenance Sensor Dataset",
        "data_source": "Synthetic digital twin simulator",
        "random_seed": random_seed,
        "number_of_machines": number_of_machines,
        "cycles_per_machine": cycles_per_machine,
        "requested_fault_rate": fault_rate,
        "total_observations": total_rows,
        "normal_observations": normal_count,
        "anomaly_observations": anomaly_count,
        "actual_anomaly_rate": round(
            anomaly_count / total_rows, 4
        ),
        "fault_counts": fault_counts,
        "machine_status_counts": status_counts,
        "columns": COLUMNS,
        "output_file": str(output),
        "limitations": [
            "All sensor readings are simulated.",
            "Fault labels are generated by controlled fault injection.",
            "Synthetic anomaly labels are not physical failure diagnoses.",
            "The dataset is not independently validated industrial data.",
        ],
    }

    summary_path = output.parent / "dataset_summary.json"

    import json

    with summary_path.open("w", encoding="utf-8") as file:
        json.dump(summary, file, indent=4)

    print("=" * 75)
    print("INDUSTRIAL SENSOR DATASET GENERATION")
    print("=" * 75)

    print(f"Machines: {number_of_machines}")
    print(f"Cycles per machine: {cycles_per_machine}")
    print(f"Total observations: {total_rows}")
    print(f"Normal observations: {normal_count}")
    print(f"Anomaly observations: {anomaly_count}")
    print(f"Actual anomaly rate: {anomaly_count / total_rows:.2%}")

    print("\n===== FAULT DISTRIBUTION =====")

    for fault, count in fault_counts.items():
        print(f"{fault}: {count}")

    print("\n===== MACHINE STATUS DISTRIBUTION =====")

    for status, count in status_counts.items():
        print(f"{status}: {count}")

    print("\n===== OUTPUT FILES =====")
    print(f"Dataset: {output.resolve()}")
    print(f"Summary: {summary_path.resolve()}")


if __name__ == "__main__":

    parser = argparse.ArgumentParser(
        description="Generate synthetic industrial sensor data."
    )

    parser.add_argument("--machines", type=int, default=20)
    parser.add_argument("--cycles", type=int, default=500)
    parser.add_argument("--fault-rate", type=float, default=0.10)
    parser.add_argument("--seed", type=int, default=42)

    args = parser.parse_args()

    generate_dataset(
        number_of_machines=args.machines,
        cycles_per_machine=args.cycles,
        fault_rate=args.fault_rate,
        random_seed=args.seed,
    )
