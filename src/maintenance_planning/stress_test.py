
"""
MAINTENANCE OPTIMIZATION STRESS TEST ENGINE

Tests scheduling scalability at:
7, 14, 21, 35 and 50 work orders.

Each workload size is tested with three reproducible seeds.

Compares:
- PRIORITY_FIRST
- SHORTEST_PROCESSING_TIME
- SEVERITY_FIRST
- FIFO
- OR_TOOLS_OPTIMAL

Synthetic workloads are generated by reusing and varying
existing maintenance work-order templates.

These experiments test scheduling scalability, not
real-world industrial performance.
"""

import csv
import json
import random
import statistics
import time

from pathlib import Path

from src.maintenance_planning.optimization import load_plan
from src.maintenance_planning.ortools_optimizer import (
    prepare_jobs,
    simulate_heuristic,
    optimize_with_ortools,
    STRATEGIES,
    TIME_SCALE,
    RANDOM_SEED,
)


ROOT = Path(__file__).resolve().parents[2]

OUTPUT_JSON = ROOT / "reports" / "maintenance_stress_test.json"
OUTPUT_CSV = ROOT / "reports" / "maintenance_stress_test.csv"

WORKLOAD_SIZES = [7, 14, 21, 35, 50]
REPEATS_PER_SIZE = 3

STRESS_SOLVER_TIME_LIMIT_SECONDS = 2.0

ALL_STRATEGIES = STRATEGIES + ["OR_TOOLS_OPTIMAL"]


# ---------------------------------------------------------
# SYNTHETIC WORKLOAD GENERATION
# ---------------------------------------------------------

def generate_workload_templates(plan):
    templates = plan.get("work_orders", [])

    if not templates:
        raise ValueError(
            "The maintenance plan contains no work orders."
        )

    required = [
        "machine_id",
        "severity",
        "priority_score",
        "estimated_duration_hours",
        "estimated_total_cost",
        "estimated_downtime_hours",
    ]

    for index, template in enumerate(templates):
        for field in required:
            if field not in template:
                raise ValueError(
                    f"Work-order template {index} is missing {field}."
                )

    return templates


def generate_synthetic_workload(
    templates,
    job_count,
    seed,
):
    """
    Generate a deterministic workload using existing templates.

    Each generated machine gets a unique identifier.
    Durations remain in half-hour increments.
    Severity and maintenance type are inherited from templates.

    This does not rerun machine diagnostics or create
    independently simulated equipment failures.
    """

    if job_count < 1:
        raise ValueError("job_count must be positive.")

    rng = random.Random(seed)

    jobs = []

    for index in range(job_count):
        template = templates[index % len(templates)]

        job = dict(template)

        original_duration = float(
            template["estimated_duration_hours"]
        )

        duration_multiplier = rng.uniform(0.75, 1.25)

        varied_duration = max(
            0.5,
            round(
                original_duration
                * duration_multiplier
                * TIME_SCALE
            ) / TIME_SCALE,
        )

        duration_ratio = (
            varied_duration / original_duration
        )

        job["machine_id"] = (
            f"STRESS-{job_count:02d}-"
            f"{index + 1:03d}"
        )

        job["work_order_id"] = (
            f"STRESS-WO-{job_count:02d}-"
            f"{index + 1:03d}"
        )

        job["estimated_duration_hours"] = varied_duration

        job["priority_score"] = max(
            1,
            int(
                template["priority_score"]
                + rng.randint(-10, 10)
            ),
        )

        # Keep estimated cost and downtime internally
        # consistent with the varied duration.
        job["estimated_total_cost"] = round(
            float(template["estimated_total_cost"])
            * duration_ratio,
            2,
        )

        job["estimated_downtime_hours"] = round(
            float(template["estimated_downtime_hours"])
            * duration_ratio,
            2,
        )

        job["synthetic_template_machine_id"] = (
            template["machine_id"]
        )

        jobs.append(job)

    return jobs


# ---------------------------------------------------------
# SCHEDULE VALIDATION
# ---------------------------------------------------------

def validate_schedule(result, expected_job_count):
    jobs = result["scheduled_work_orders"]

    if len(jobs) != expected_job_count:
        return False

    machine_ids = [
        job["machine_id"]
        for job in jobs
    ]

    if len(machine_ids) != len(set(machine_ids)):
        return False

    by_technician = {}

    for job in jobs:
        technician = job["assigned_technician"]

        by_technician.setdefault(
            technician,
            [],
        ).append(job)

        if job["finish_units"] < job["start_units"]:
            return False

    for technician_jobs in by_technician.values():
        technician_jobs.sort(
            key=lambda job: job["start_units"]
        )

        for previous, current in zip(
            technician_jobs,
            technician_jobs[1:],
        ):
            if (
                previous["finish_units"]
                > current["start_units"]
            ):
                return False

    return True


# ---------------------------------------------------------
# RUN ONE WORKLOAD EXPERIMENT
# ---------------------------------------------------------

def run_one_experiment(
    templates,
    job_count,
    repeat_number,
):
    seed = (
        RANDOM_SEED
        + job_count * 100
        + repeat_number
    )

    raw_jobs = generate_synthetic_workload(
        templates,
        job_count,
        seed,
    )

    jobs = prepare_jobs(raw_jobs)

    results = []

    # Four heuristic baselines.
    for strategy in STRATEGIES:
        started = time.perf_counter()

        result = simulate_heuristic(
            jobs,
            strategy,
        )

        elapsed = time.perf_counter() - started

        result["execution_time_seconds"] = round(
            elapsed,
            6,
        )

        result["schedule_valid"] = validate_schedule(
            result,
            job_count,
        )

        results.append(result)

    # Constraint-based optimizer.
    started = time.perf_counter()

    try:
        result = optimize_with_ortools(
            jobs,
            time_limit=STRESS_SOLVER_TIME_LIMIT_SECONDS,
        )

        elapsed = time.perf_counter() - started

        result["execution_time_seconds"] = round(
            elapsed,
            6,
        )

        result["schedule_valid"] = validate_schedule(
            result,
            job_count,
        )

        result["solver_error"] = None

    except Exception as exc:
        elapsed = time.perf_counter() - started

        result = {
            "strategy": "OR_TOOLS_OPTIMAL",
            "solver_status": "NO_SOLUTION",
            "optimality_proven": False,
            "execution_time_seconds": round(
                elapsed,
                6,
            ),
            "solver_wall_time_seconds": None,
            "schedule_valid": False,
            "solver_error": str(exc),
            "scheduled_work_orders": [],
        }

    results.append(result)

    return {
        "experiment_id": (
            f"SIZE-{job_count:03d}-"
            f"REPEAT-{repeat_number:02d}"
        ),
        "job_count": job_count,
        "repeat_number": repeat_number,
        "seed": seed,
        "scenario_origin": (
            "SYNTHETIC_VARIATIONS_OF_EXISTING_WORK_ORDER_TEMPLATES"
        ),
        "results": results,
    }


# ---------------------------------------------------------
# RUN FULL STRESS EXPERIMENT
# ---------------------------------------------------------

def run_stress_experiments(
    plan,
    workload_sizes=None,
    repeats=REPEATS_PER_SIZE,
):
    if workload_sizes is None:
        workload_sizes = WORKLOAD_SIZES

    templates = generate_workload_templates(plan)

    experiments = []

    total = len(workload_sizes) * repeats
    current = 0

    for job_count in workload_sizes:
        for repeat_number in range(1, repeats + 1):
            current += 1

            print(
                f"\n[{current}/{total}] "
                f"Testing {job_count} work orders "
                f"(repeat {repeat_number}/{repeats})"
            )

            experiment = run_one_experiment(
                templates,
                job_count,
                repeat_number,
            )

            experiments.append(experiment)

            ortools_result = next(
                item
                for item in experiment["results"]
                if item["strategy"] == "OR_TOOLS_OPTIMAL"
            )

            print(
                "OR-Tools status:",
                ortools_result["solver_status"],
            )

            print(
                "Optimality proven:",
                ortools_result["optimality_proven"],
            )

            print(
                "Execution time:",
                ortools_result["execution_time_seconds"],
                "seconds",
            )

    return experiments


# ---------------------------------------------------------
# AGGREGATION
# ---------------------------------------------------------

def safe_mean(values):
    return (
        round(statistics.mean(values), 4)
        if values else None
    )


def aggregate_stress_results(experiments):
    summary = {}

    job_counts = sorted({
        experiment["job_count"]
        for experiment in experiments
    })

    for job_count in job_counts:
        size_experiments = [
            experiment
            for experiment in experiments
            if experiment["job_count"] == job_count
        ]

        strategy_summary = {}

        for strategy in ALL_STRATEGIES:
            records = []

            for experiment in size_experiments:
                result = next(
                    item
                    for item in experiment["results"]
                    if item["strategy"] == strategy
                )

                records.append(result)

            valid_records = [
                item
                for item in records
                if item.get("schedule_valid", False)
            ]

            successful_solver_records = [
                item
                for item in records
                if item.get("solver_status")
                in ("OPTIMAL", "FEASIBLE")
            ]

            proven_records = [
                item
                for item in records
                if item.get("optimality_proven", False)
            ]

            strategy_summary[strategy] = {
                "total_runs": len(records),
                "valid_schedules": len(valid_records),
                "valid_schedule_rate_percentage": round(
                    len(valid_records) / len(records) * 100,
                    2,
                ),
                "successful_solver_runs": len(
                    successful_solver_records
                ),
                "optimality_proven_count": len(
                    proven_records
                ),
                "optimality_proven_rate_percentage": round(
                    len(proven_records) / len(records) * 100,
                    2,
                ),
                "average_execution_time_seconds": safe_mean([
                    item["execution_time_seconds"]
                    for item in records
                    if item.get("execution_time_seconds") is not None
                ]),
                "average_solver_time_seconds": safe_mean([
                    item["solver_wall_time_seconds"]
                    for item in records
                    if item.get("solver_wall_time_seconds") is not None
                ]),
                "average_makespan_hours": safe_mean([
                    item["makespan_hours"]
                    for item in valid_records
                    if "makespan_hours" in item
                ]),
                "average_waiting_hours": safe_mean([
                    item["average_waiting_hours"]
                    for item in valid_records
                    if "average_waiting_hours" in item
                ]),
                "average_critical_completion_hours": safe_mean([
                    item[
                        "critical_machine_average_completion_hours"
                    ]
                    for item in valid_records
                    if (
                        "critical_machine_average_completion_hours"
                        in item
                    )
                ]),
                "average_utilization_percentage": safe_mean([
                    item["technician_utilization_percentage"]
                    for item in valid_records
                    if "technician_utilization_percentage" in item
                ]),
            }

        summary[str(job_count)] = {
            "work_order_count": job_count,
            "repeat_count": len(size_experiments),
            "strategies": strategy_summary,
        }

    return summary


# ---------------------------------------------------------
# COMPARATIVE ANALYSIS
# ---------------------------------------------------------

def calculate_scalability_findings(summary):
    findings = []

    for size, size_data in summary.items():
        strategies = size_data["strategies"]

        ortools = strategies["OR_TOOLS_OPTIMAL"]

        valid_ortools = (
            ortools["valid_schedules"] > 0
        )

        if not valid_ortools:
            findings.append({
                "work_order_count": int(size),
                "finding": "OR_TOOLS_DID_NOT_RETURN_VALID_SCHEDULE",
            })
            continue

        baseline_makespans = [
            strategies[strategy]["average_makespan_hours"]
            for strategy in STRATEGIES
            if (
                strategies[strategy]["average_makespan_hours"]
                is not None
            )
        ]

        ortools_makespan = ortools[
            "average_makespan_hours"
        ]

        best_baseline = (
            min(baseline_makespans)
            if baseline_makespans else None
        )

        improvement = None

        if (
            best_baseline is not None
            and best_baseline > 0
        ):
            improvement = round(
                (
                    best_baseline - ortools_makespan
                ) / best_baseline * 100,
                2,
            )

        findings.append({
            "work_order_count": int(size),
            "ortools_average_makespan_hours": (
                ortools_makespan
            ),
            "best_heuristic_average_makespan_hours": (
                best_baseline
            ),
            "makespan_improvement_vs_best_heuristic_percentage": (
                improvement
            ),
            "ortools_optimality_proven_rate_percentage": (
                ortools[
                    "optimality_proven_rate_percentage"
                ]
            ),
            "ortools_average_execution_time_seconds": (
                ortools[
                    "average_execution_time_seconds"
                ]
            ),
            "finding": "MEASURED",
        })

    return findings


# ---------------------------------------------------------
# VALIDATION
# ---------------------------------------------------------

def validate_stress_experiments(experiments):
    checks = {}

    checks["all_requested_workload_sizes_present"] = (
        set(WORKLOAD_SIZES).issubset({
            experiment["job_count"]
            for experiment in experiments
        })
    )

    checks["correct_number_of_experiments"] = (
        len(experiments)
        == len(WORKLOAD_SIZES) * REPEATS_PER_SIZE
    )

    checks["every_experiment_has_five_strategies"] = all(
        len(experiment["results"]) == 5
        for experiment in experiments
    )

    checks["experiment_ids_are_unique"] = (
        len({
            experiment["experiment_id"]
            for experiment in experiments
        }) == len(experiments)
    )

    checks["heuristic_schedules_are_valid"] = all(
        result["schedule_valid"]
        for experiment in experiments
        for result in experiment["results"]
        if result["strategy"] in STRATEGIES
    )

    checks["ortools_schedules_are_valid_when_returned"] = all(
        result["schedule_valid"]
        for experiment in experiments
        for result in experiment["results"]
        if (
            result["strategy"] == "OR_TOOLS_OPTIMAL"
            and result["solver_status"] in ("OPTIMAL", "FEASIBLE")
        )
    )

    checks["solver_statuses_are_recorded"] = all(
        bool(result.get("solver_status"))
        for experiment in experiments
        for result in experiment["results"]
        if result["strategy"] == "OR_TOOLS_OPTIMAL"
    )

    checks["work_order_counts_match_experiment_size"] = all(
        len(result["scheduled_work_orders"])
        == experiment["job_count"]
        for experiment in experiments
        for result in experiment["results"]
        if result.get("schedule_valid", False)
    )

    return {
        "passed": sum(checks.values()),
        "total": len(checks),
        "all_passed": all(checks.values()),
        "checks": checks,
    }


# ---------------------------------------------------------
# EXPORT CSV
# ---------------------------------------------------------

def export_stress_csv(experiments):
    fields = [
        "experiment_id",
        "job_count",
        "repeat_number",
        "seed",
        "strategy",
        "solver_status",
        "optimality_proven",
        "schedule_valid",
        "execution_time_seconds",
        "solver_wall_time_seconds",
        "makespan_hours",
        "average_waiting_hours",
        "critical_machine_average_completion_hours",
        "technician_utilization_percentage",
        "solver_error",
    ]

    with OUTPUT_CSV.open(
        "w",
        newline="",
        encoding="utf-8",
    ) as file:
        writer = csv.DictWriter(
            file,
            fieldnames=fields,
        )

        writer.writeheader()

        for experiment in experiments:
            for result in experiment["results"]:
                row = {
                    "experiment_id": experiment["experiment_id"],
                    "job_count": experiment["job_count"],
                    "repeat_number": experiment["repeat_number"],
                    "seed": experiment["seed"],
                }

                for field in fields[4:]:
                    row[field] = result.get(field, "")

                writer.writerow(row)


# ---------------------------------------------------------
# MAIN
# ---------------------------------------------------------

def main():
    print("\n" + "=" * 85)
    print("MAINTENANCE OPTIMIZATION STRESS TEST ENGINE")
    print("=" * 85)

    plan = load_plan()

    experiments = run_stress_experiments(
        plan,
        workload_sizes=WORKLOAD_SIZES,
        repeats=REPEATS_PER_SIZE,
    )

    summary = aggregate_stress_results(
        experiments
    )

    findings = calculate_scalability_findings(
        summary
    )

    validation = validate_stress_experiments(
        experiments
    )

    output = {
        "platform": "MAINTENANCE_OPTIMIZATION_STRESS_TEST",
        "workload_sizes": WORKLOAD_SIZES,
        "repeats_per_size": REPEATS_PER_SIZE,
        "total_experiments": len(experiments),
        "solver_time_limit_seconds": (
            STRESS_SOLVER_TIME_LIMIT_SECONDS
        ),
        "technician_count": 2,
        "time_scale": TIME_SCALE,
        "scenario_generation": {
            "origin": (
                "EXISTING_SYNTHETIC_MAINTENANCE_WORK_ORDER_TEMPLATES"
            ),
            "duration_variation": "0.75x TO 1.25x",
            "priority_variation": "MINUS 10 TO PLUS 10",
            "independent_real_world_datasets": False,
        },
        "strategy_summary_by_workload_size": summary,
        "scalability_findings": findings,
        "validation": validation,
        "experiment_details": experiments,
    }

    OUTPUT_JSON.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    with OUTPUT_JSON.open(
        "w",
        encoding="utf-8",
    ) as file:
        json.dump(output, file, indent=4)

    export_stress_csv(experiments)

    print("\n" + "=" * 85)
    print("STRESS TEST SUMMARY")
    print("=" * 85)

    for size, size_data in summary.items():
        print(f"\n===== {size} WORK ORDERS =====")

        for strategy, metrics in size_data["strategies"].items():
            print(f"\n{strategy}")

            print(
                "Valid schedules:",
                metrics["valid_schedules"],
                "/",
                metrics["total_runs"],
            )

            print(
                "Optimality proven:",
                metrics["optimality_proven_count"],
                "/",
                metrics["total_runs"],
            )

            print(
                "Average execution time:",
                metrics["average_execution_time_seconds"],
            )

            print(
                "Average makespan:",
                metrics["average_makespan_hours"],
            )

    print("\n===== SCALABILITY FINDINGS =====")

    for finding in findings:
        print(finding)

    print("\n===== VALIDATION =====")

    for name, passed in validation["checks"].items():
        print(
            f"{name}: "
            f"{'PASSED' if passed else 'FAILED'}"
        )

    print(
        f"\nValidation: {validation['passed']}/"
        f"{validation['total']}"
    )

    print("\nJSON:", OUTPUT_JSON)
    print("CSV:", OUTPUT_CSV)

    if not validation["all_passed"]:
        raise RuntimeError(
            "Stress-test validation failed."
        )

    print("\nSTRESS TEST COMPLETED.")


if __name__ == "__main__":
    main()
